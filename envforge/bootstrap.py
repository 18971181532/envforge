"""Bootstrap script generation — recreate an environment on a new machine."""
import os
import platform
from pathlib import Path


def generate_bootstrap(profile, output_path=None, shell="auto"):
    """Generate a bootstrap script that recreates the environment.

    Args:
        profile: The environment profile to recreate.
        output_path: Where to write the script. If None, returns the script content.
        shell: Target shell — 'bash', 'powershell', 'cmd', or 'auto' (detect from OS).

    Returns:
        The script content as a string (and writes to output_path if provided).
    """
    if shell == "auto":
        if platform.system() == "Windows":
            shell = "powershell"
        else:
            shell = "bash"

    if shell == "powershell":
        script = _generate_powershell(profile)
    elif shell == "bash":
        script = _generate_bash(profile)
    elif shell == "cmd":
        script = _generate_cmd(profile)
    else:
        raise ValueError(f"Unsupported shell: {shell}")

    if output_path:
        Path(output_path).write_text(script, encoding="utf-8")
    return script


def _header(profile, shell_type):
    name = profile.get("name", "envforge")
    captured = profile.get("captured_at_iso", "unknown")
    if shell_type == "powershell":
        return f"""# EnvForge Bootstrap Script
# Profile: {name}
# Captured: {captured}
# Generated by EnvForge
# Run: powershell -ExecutionPolicy Bypass -File bootstrap.ps1

$ErrorActionPreference = "Continue"
$ProgressPreference = "SilentlyContinue"

Write-Host "=== EnvForge Bootstrap: {name} ===" -ForegroundColor Cyan
Write-Host ""

"""
    elif shell_type == "bash":
        return f"""#!/usr/bin/env bash
# EnvForge Bootstrap Script
# Profile: {name}
# Captured: {captured}
# Generated by EnvForge
# Run: bash bootstrap.sh

set -e

echo "=== EnvForge Bootstrap: {name} ==="
echo ""

"""
    else:  # cmd
        return f"""@echo off
REM EnvForge Bootstrap Script
REM Profile: {name}
REM Captured: {captured}
REM Generated by EnvForge
REM Run: bootstrap.bat

echo === EnvForge Bootstrap: {name} ===
echo.

"""


def _generate_powershell(profile):
    lines = [_header(profile, "powershell")]

    # Package managers
    packages = profile.get("packages", {})

    # pip packages
    if "pip" in packages and packages["pip"]:
        lines.append("# --- Python packages (pip) ---")
        lines.append("Write-Host 'Installing Python packages...' -ForegroundColor Yellow")
        lines.append("if (Get-Command pip -ErrorAction SilentlyContinue) {")
        for pkg in packages["pip"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}=={version}" if version else name
            lines.append(f"  pip install {spec}")
        lines.append("} else {")
        lines.append("  Write-Host 'pip not found, skipping Python packages' -ForegroundColor DarkGray")
        lines.append("}")
        lines.append("")

    # npm global packages
    if "npm_global" in packages and packages["npm_global"]:
        lines.append("# --- Node.js global packages (npm) ---")
        lines.append("Write-Host 'Installing npm global packages...' -ForegroundColor Yellow")
        lines.append("if (Get-Command npm -ErrorAction SilentlyContinue) {")
        for pkg in packages["npm_global"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}@{version}" if version else name
            lines.append(f"  npm install -g {spec}")
        lines.append("} else {")
        lines.append("  Write-Host 'npm not found, skipping' -ForegroundColor DarkGray")
        lines.append("}")
        lines.append("")

    # cargo packages
    if "cargo" in packages and packages["cargo"]:
        lines.append("# --- Rust packages (cargo) ---")
        lines.append("Write-Host 'Installing cargo packages...' -ForegroundColor Yellow")
        lines.append("if (Get-Command cargo -ErrorAction SilentlyContinue) {")
        for pkg in packages["cargo"]:
            name = pkg.get("name", "")
            lines.append(f"  cargo install {name}")
        lines.append("} else {")
        lines.append("  Write-Host 'cargo not found, skipping' -ForegroundColor DarkGray")
        lines.append("}")
        lines.append("")

    # Git config
    git_config = profile.get("git_config", {})
    if git_config:
        lines.append("# --- Git configuration ---")
        lines.append("Write-Host 'Configuring git...' -ForegroundColor Yellow")
        lines.append("if (Get-Command git -ErrorAction SilentlyContinue) {")
        for key, value in git_config.items():
            escaped = value.replace("'", "''")
            lines.append(f"  git config --global {key} '{escaped}'")
        lines.append("}")
        lines.append("")

    # Environment variables (non-system)
    env_vars = profile.get("env_vars", {})
    user_env_keys = [k for k in env_vars if k.upper() not in
                     ("PATH", "HOME", "USER", "USERNAME", "SHELL", "TEMP", "TMP",
                      "SYSTEMROOT", "PROGRAMFILES", "PROGRAMFILES(X86)", "PUBLIC",
                      "DRIVERDATA", "COMMONPROGRAMFILES", "COMSPEC", "PSMODULEPATH",
                      "LOCALAPPDATA", "APPDATA", "USERPROFILE")]
    if user_env_keys:
        lines.append("# --- User environment variables ---")
        lines.append("Write-Host 'Setting environment variables...' -ForegroundColor Yellow")
        for key in sorted(user_env_keys):
            value = env_vars[key]
            escaped = value.replace("'", "''")
            lines.append(f"[Environment]::SetEnvironmentVariable('{key}', '{escaped}', 'User')")
        lines.append("")

    lines.append("Write-Host ''")
    lines.append("Write-Host '=== Bootstrap complete ===' -ForegroundColor Green")
    lines.append("Write-Host 'Note: Some tools may require manual installation.' -ForegroundColor DarkGray")
    lines.append("")
    return "\n".join(lines)


def _generate_bash(profile):
    lines = [_header(profile, "bash")]

    packages = profile.get("packages", {})

    # Detect package manager
    lines.append("# Detect OS package manager")
    lines.append("if command -v apt-get &> /dev/null; then PKG_MANAGER=\"apt\";")
    lines.append("elif command -v brew &> /dev/null; then PKG_MANAGER=\"brew\";")
    lines.append("elif command -v dnf &> /dev/null; then PKG_MANAGER=\"dnf\";")
    lines.append("elif command -v pacman &> /dev/null; then PKG_MANAGER=\"pacman\";")
    lines.append("else PKG_MANAGER=\"unknown\"; fi")
    lines.append("echo \"Package manager: $PKG_MANAGER\"")
    lines.append("")

    # pip
    if "pip" in packages and packages["pip"]:
        lines.append("# --- Python packages (pip) ---")
        lines.append("echo 'Installing Python packages...'")
        lines.append("if command -v pip3 &> /dev/null; then PIP=pip3; elif command -v pip &> /dev/null; then PIP=pip; else PIP=\"\"; fi")
        lines.append("if [ -n \"$PIP\" ]; then")
        for pkg in packages["pip"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}=={version}" if version else name
            lines.append(f"  $PIP install --user {spec}")
        lines.append("else echo 'pip not found, skipping'; fi")
        lines.append("")

    # npm
    if "npm_global" in packages and packages["npm_global"]:
        lines.append("# --- Node.js global packages ---")
        lines.append("echo 'Installing npm global packages...'")
        lines.append("if command -v npm &> /dev/null; then")
        for pkg in packages["npm_global"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}@{version}" if version else name
            lines.append(f"  npm install -g {spec}")
        lines.append("else echo 'npm not found, skipping'; fi")
        lines.append("")

    # cargo
    if "cargo" in packages and packages["cargo"]:
        lines.append("# --- Rust packages (cargo) ---")
        lines.append("echo 'Installing cargo packages...'")
        lines.append("if command -v cargo &> /dev/null; then")
        for pkg in packages["cargo"]:
            lines.append(f"  cargo install {pkg.get('name', '')}")
        lines.append("else echo 'cargo not found, skipping'; fi")
        lines.append("")

    # Git config
    git_config = profile.get("git_config", {})
    if git_config:
        lines.append("# --- Git configuration ---")
        lines.append("echo 'Configuring git...'")
        lines.append("if command -v git &> /dev/null; then")
        for key, value in git_config.items():
            escaped = value.replace("'", "'\\''")
            lines.append(f"  git config --global {key} '{escaped}'")
        lines.append("fi")
        lines.append("")

    # Env vars for shell rc
    user_env_keys = [k for k in profile.get("env_vars", {}) if k.upper() not in
                     ("PATH", "HOME", "USER", "SHELL", "LANG", "TERM", "TMPDIR")]
    if user_env_keys:
        lines.append("# --- Environment variables (add to ~/.bashrc or ~/.zshrc) ---")
        lines.append("ENV_FILE=\"$HOME/.envforge_env\"")
        lines.append("cat > \"$ENV_FILE\" << 'ENVEOF'")
        for key in sorted(user_env_keys):
            value = profile["env_vars"][key]
            escaped = value.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'export {key}="{escaped}"')
        lines.append("ENVEOF")
        lines.append("echo 'Environment variables written to ~/.envforge_env'")
        lines.append("echo 'Add \"source ~/.envforge_env\" to your shell rc file'")
        lines.append("")

    lines.append("echo ''")
    lines.append("echo '=== Bootstrap complete ==='")
    lines.append("echo 'Note: Some tools may require manual installation.'")
    lines.append("")
    return "\n".join(lines)


def _generate_cmd(profile):
    lines = [_header(profile, "cmd")]

    packages = profile.get("packages", {})

    if "pip" in packages and packages["pip"]:
        lines.append("REM --- Python packages (pip) ---")
        lines.append("echo Installing Python packages...")
        for pkg in packages["pip"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}=={version}" if version else name
            lines.append(f"pip install {spec}")
        lines.append("")

    if "npm_global" in packages and packages["npm_global"]:
        lines.append("REM --- npm global packages ---")
        lines.append("echo Installing npm global packages...")
        for pkg in packages["npm_global"]:
            name = pkg.get("name", "")
            version = pkg.get("version", "")
            spec = f"{name}@{version}" if version else name
            lines.append(f"npm install -g {spec}")
        lines.append("")

    git_config = profile.get("git_config", {})
    if git_config:
        lines.append("REM --- Git configuration ---")
        for key, value in git_config.items():
            lines.append(f'git config --global {key} "{value}"')
        lines.append("")

    lines.append("echo.")
    lines.append("echo === Bootstrap complete ===")
    lines.append("")
    return "\n".join(lines)


def generate_activation_script(profile, shell="auto"):
    """Generate a shell activation script that sets env vars for current session.

    Unlike bootstrap, this only sets environment variables in the current shell,
    doesn't install packages.
    """
    if shell == "auto":
        if platform.system() == "Windows":
            shell = "powershell"
        else:
            shell = "bash"

    env_vars = profile.get("env_vars", {})
    lines = []

    if shell == "powershell":
        lines.append("# EnvForge activation script")
        lines.append(f"# Profile: {profile.get('name', '?')}")
        lines.append("")
        for key, value in sorted(env_vars.items()):
            if key.upper() == "PATH":
                continue  # Don't override PATH
            escaped = value.replace("'", "''")
            lines.append(f"$env:{key} = '{escaped}'")
        lines.append("")
        lines.append(f"Write-Host 'Activated environment: {profile.get('name', '?')}' -ForegroundColor Green")

    elif shell == "bash":
        lines.append("#!/usr/bin/env bash")
        lines.append("# EnvForge activation script")
        lines.append(f"# Profile: {profile.get('name', '?')}")
        lines.append("# Usage: source activate.sh")
        lines.append("")
        for key, value in sorted(env_vars.items()):
            if key.upper() == "PATH":
                continue
            escaped = value.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'export {key}="{escaped}"')
        lines.append("")
        lines.append(f'echo "Activated environment: {profile.get("name", "?")}"')

    return "\n".join(lines)
